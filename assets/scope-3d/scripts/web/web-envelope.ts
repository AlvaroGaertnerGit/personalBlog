// Scope 3D — the site's motion envelope, measured once in Node from the GLB the
// site actually ships (public/scope/scope.glb), instead of at every page load
// (~380 ms of main thread, measured in Chrome).
//
//   node assets/scope-3d/scripts/web/web-envelope.ts --write
//
// rewrites src/components/scope-3d/engine/scope-3d-web-envelope.ts. Run it after
// re-exporting or re-optimising the GLB; scope-3d-framing.test.ts fails until you do.

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

import { MeshoptDecoder } from "three/addons/libs/meshopt_decoder.module.js"
import { GLTFLoader } from "three/addons/loaders/GLTFLoader.js"

import { Scope3DAnimator } from "../../../../src/components/scope-3d/engine/scope-3d-animator.ts"
import {
  measureMotionEnvelope,
  reduceEnvelope,
  SCOPE_3D_WEB_VIEW_DIRECTION,
  type Scope3DEnvelopeData,
  type Scope3DMotionEnvelope,
} from "../../../../src/components/scope-3d/engine/scope-3d-framing.ts"
import { Scope3DSecondary } from "../../../../src/components/scope-3d/engine/scope-3d-secondary.ts"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../../..")
export const WEB_GLB = path.join(ROOT, "public/scope/scope.glb")
const OUT = path.join(ROOT, "src/components/scope-3d/engine/scope-3d-web-envelope.ts")

/** The full envelope, measured exactly as the viewer does it in the browser. */
export async function measureWebEnvelope(glbPath = WEB_GLB): Promise<Scope3DMotionEnvelope> {
  const file = fs.readFileSync(glbPath)
  const data = file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength)
  const gltf = await new GLTFLoader().setMeshoptDecoder(MeshoptDecoder).parseAsync(data, "")
  const animator = new Scope3DAnimator(gltf.scene, gltf.animations)
  // Deterministic: the drift phases are the only randomness, and life is off while measuring.
  const secondary = new Scope3DSecondary(gltf.scene, () => 0.5)
  return measureMotionEnvelope(gltf.scene, animator, secondary, SCOPE_3D_WEB_VIEW_DIRECTION)
}

/** 0.1 mm: far below a pixel at web sizes, and short in source. */
const round = (v: number) => Math.round(v * 1e4) / 1e4 || 0 // no -0: the source prints it as 0

export function toData({ points, box }: Scope3DMotionEnvelope): Scope3DEnvelopeData {
  const xyz = (v: { x: number; y: number; z: number }) => [round(v.x), round(v.y), round(v.z)] as const
  return { points: points.map(xyz), box: [xyz(box.min), xyz(box.max)] }
}

async function write() {
  const reduced = toData(reduceEnvelope(await measureWebEnvelope(), SCOPE_3D_WEB_VIEW_DIRECTION))
  const source = `// GENERATED by assets/scope-3d/scripts/web/web-envelope.ts --write — do not edit.
// The few silhouette points of public/scope/scope.glb's full motion (every
// clip, max amplitude, antenna spring) that can touch the site camera's
// frame. The viewer frames on them instead of measuring at load;
// scope-3d-framing.test.ts checks they still match the GLB.

import { envelopeFromData } from "./scope-3d-framing.ts"

export const SCOPE_3D_WEB_ENVELOPE = envelopeFromData({
  points: [
${reduced.points.map((p) => `    [${p.join(", ")}],`).join("\n")}
  ],
  box: [[${reduced.box[0].join(", ")}], [${reduced.box[1].join(", ")}]],
})
`
  fs.writeFileSync(OUT, source)
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${reduced.points.length} points`)
}

// Only as a script with --write (the framing test imports this module too).
if (process.argv.includes("--write")) await write()
