// Bundles the prototype (src/main.ts -> dist/app.js) with the esbuild that is
// already in the repo's node_modules (a transitive dependency): no new package.
//   node docs/redesign/scope-world/prototype/tools/build.mjs [--watch]
import { createRequire } from "node:module"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const proto = path.resolve(here, "..")
const repo = path.resolve(proto, "..", "..", "..", "..")
const require = createRequire(path.join(repo, "node_modules", ".pnpm", "node_modules", "_"))
const esbuild = require("esbuild")

const options = {
  entryPoints: [path.join(proto, "src", "main.ts")],
  outfile: path.join(proto, "dist", "app.js"),
  bundle: true,
  format: "esm",
  target: "es2022",
  minify: true,
  sourcemap: true,
  legalComments: "none",
  banner: { js: "/* eslint-disable */ // generated by tools/build.mjs — Scope World prototype bundle" },
  logLevel: "info",
  nodePaths: [path.join(repo, "node_modules")],
}

if (process.argv.includes("--watch")) {
  const ctx = await esbuild.context(options)
  await ctx.watch()
} else {
  const result = await esbuild.build({ ...options, metafile: true })
  const out = Object.entries(result.metafile.outputs).find(([f]) => f.endsWith("app.js"))
  console.log(`[build] dist/app.js ${(out[1].bytes / 1024).toFixed(0)} KB`)
}
