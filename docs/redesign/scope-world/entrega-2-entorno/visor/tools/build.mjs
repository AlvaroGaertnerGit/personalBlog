// Bundles the environment viewer (src/main.ts -> dist/visor.js) with the esbuild already
// in the repo's node_modules, like the 1.0 prototype. No new package.
//   node docs/redesign/scope-world/entrega-2-entorno/visor/tools/build.mjs
import { createRequire } from "node:module"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const visor = path.resolve(here, "..")
const repo = path.resolve(visor, "..", "..", "..", "..", "..")
const require = createRequire(path.join(repo, "node_modules", ".pnpm", "node_modules", "_"))
const esbuild = require("esbuild")

const result = await esbuild.build({
  entryPoints: [path.join(visor, "src", "main.ts")],
  outfile: path.join(visor, "dist", "visor.js"),
  bundle: true,
  format: "esm",
  target: "es2022",
  minify: true,
  sourcemap: true,
  legalComments: "none",
  banner: { js: "/* eslint-disable */ // generated by tools/build.mjs — Scope World environment study" },
  nodePaths: [path.join(repo, "node_modules")],
  metafile: true,
  logLevel: "warning",
})
const out = Object.entries(result.metafile.outputs).find(([f]) => f.endsWith("visor.js"))
console.log(`[build] dist/visor.js ${(out[1].bytes / 1024).toFixed(0)} KB`)
