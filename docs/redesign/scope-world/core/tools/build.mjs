// Bundles one Scope World page with the esbuild already in the repo's node_modules
// (a transitive dependency, as since the 1.0 prototype). No new package.
//   node docs/redesign/scope-world/core/tools/build.mjs <entry.ts> <out.js> [label]
// The pages' own tools/build.mjs call this with their entry and output.
import { createRequire } from "node:module"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, "..", "..", "..", "..", "..")
const require = createRequire(path.join(repo, "node_modules", ".pnpm", "node_modules", "_"))
const esbuild = require("esbuild")

export async function build(entry, outfile, label = "Scope World") {
  const result = await esbuild.build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    format: "esm",
    target: "es2022",
    minify: true,
    sourcemap: true,
    legalComments: "none",
    banner: { js: `/* eslint-disable */ // generated by tools/build.mjs — ${label}` },
    nodePaths: [path.join(repo, "node_modules")],
    metafile: true,
    logLevel: "warning",
  })
  const out = Object.entries(result.metafile.outputs).find(([f]) => f.endsWith(path.basename(outfile)))
  console.log(`[build] ${path.relative(process.cwd(), outfile)} ${(out[1].bytes / 1024).toFixed(0)} KB`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [entry, out, label] = process.argv.slice(2)
  await build(path.resolve(entry), path.resolve(out), label)
}
